begin;

create table if not exists public.user_favorites (
  favorite_id bigint generated by default as identity primary key,
  auth_user_id uuid not null references auth.users (id) on delete cascade,
  manga_id text not null,
  title text not null,
  href text not null default '',
  image text not null default '',
  note text not null default '',
  category text not null default 'ทั่วไป',
  type text not null default 'manga',
  created_at timestamptz not null default now(),
  unique (auth_user_id, manga_id)
);

alter table public.user_favorites
  alter column manga_id type text using manga_id::text;

alter table public.user_favorites
  add column if not exists title text not null default '',
  add column if not exists href text not null default '',
  add column if not exists image text not null default '',
  add column if not exists note text not null default '',
  add column if not exists category text not null default 'ทั่วไป',
  add column if not exists type text not null default 'manga';

update public.user_favorites
set title = manga_id
where title = '';

create index if not exists user_favorites_auth_user_created_idx
  on public.user_favorites (auth_user_id, created_at desc);

create unique index if not exists user_favorites_auth_user_manga_uidx
  on public.user_favorites (auth_user_id, manga_id);

create table if not exists public.user_saved_vocab (
  saved_vocab_id bigint generated by default as identity primary key,
  auth_user_id uuid not null references auth.users (id) on delete cascade,
  vocab_id integer,
  kanji text,
  kana text,
  word text not null,
  level text not null default '',
  reading text not null default '',
  meaning text not null default '',
  meaning_th text not null default '',
  created_at timestamptz not null default now(),
  unique (auth_user_id, word, level)
);

alter table public.user_saved_vocab
  add column if not exists vocab_id integer,
  add column if not exists kanji text,
  add column if not exists kana text,
  add column if not exists word text,
  add column if not exists level text not null default '',
  add column if not exists reading text not null default '',
  add column if not exists meaning text not null default '',
  add column if not exists meaning_th text not null default '';

update public.user_saved_vocab
set word = coalesce(nullif(word, ''), nullif(kanji, ''), nullif(kana, ''), ''),
    reading = coalesce(nullif(reading, ''), kana, '')
where word is null or word = '' or reading = '';

alter table public.user_saved_vocab
  alter column word set not null;

delete from public.user_saved_vocab as older
using public.user_saved_vocab as newer
where older.saved_vocab_id < newer.saved_vocab_id
  and older.auth_user_id = newer.auth_user_id
  and older.word = newer.word
  and older.level = newer.level;

create index if not exists user_saved_vocab_auth_user_created_idx
  on public.user_saved_vocab (auth_user_id, created_at desc);

create unique index if not exists user_saved_vocab_auth_user_word_level_uidx
  on public.user_saved_vocab (auth_user_id, word, level);

alter table public.user_favorites enable row level security;
alter table public.user_saved_vocab enable row level security;

drop policy if exists "Users manage own favorites" on public.user_favorites;
create policy "Users manage own favorites"
  on public.user_favorites for all to authenticated
  using (auth.uid() = auth_user_id)
  with check (auth.uid() = auth_user_id);

drop policy if exists "Users manage own saved vocab" on public.user_saved_vocab;
create policy "Users manage own saved vocab"
  on public.user_saved_vocab for all to authenticated
  using (auth.uid() = auth_user_id)
  with check (auth.uid() = auth_user_id);

grant select, insert, update, delete on public.user_favorites to authenticated;
grant usage, select on sequence public.user_favorites_favorite_id_seq to authenticated;
grant select, insert, update, delete on public.user_saved_vocab to authenticated;
grant usage, select on sequence public.user_saved_vocab_saved_vocab_id_seq to authenticated;

notify pgrst, 'reload schema';

commit;
