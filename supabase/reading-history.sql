create table if not exists public.reading_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  session_id text not null,
  type text not null check (type in ('manga', 'vocabulary')),
  title text not null,
  manga_id text,
  chapter text not null default '',
  page_number integer not null default 0 check (page_number >= 0),
  total_pages integer not null default 0 check (total_pages >= 0),
  duration_seconds integer not null default 0 check (duration_seconds >= 0),
  read_at timestamptz not null,
  created_at timestamptz not null default now(),
  unique (user_id, session_id)
);

create index if not exists reading_history_user_read_at_idx
  on public.reading_history (user_id, read_at desc);

alter table public.reading_history enable row level security;

drop policy if exists "Users can read their own reading history" on public.reading_history;
create policy "Users can read their own reading history"
  on public.reading_history for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can add their own reading history" on public.reading_history;
create policy "Users can add their own reading history"
  on public.reading_history for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Users can update their own reading history" on public.reading_history;
create policy "Users can update their own reading history"
  on public.reading_history for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Users can delete their own reading history" on public.reading_history;
create policy "Users can delete their own reading history"
  on public.reading_history for delete to authenticated
  using (auth.uid() = user_id);

grant select, insert, update, delete on public.reading_history to authenticated;
grant usage, select on sequence public.reading_history_id_seq to authenticated;
